def hull():
    parts = []
    # Deck / fender slab
    parts.append(cbox(-HL + 0.05, HL - 0.05, -HW, HW, hz(h_arch), hz(h_deck), 0.035))
    # Centre tub with armoured, sloped belly
    zt, zm, zb = hz(h_arch), hz(h_tub + 0.16), hz(h_tub)
    parts.append(chull([(sx * X_TUB, sy * Y_TUB, zt) for sx in (-1, 1) for sy in (-1, 1)] +
                       [(sx * X_TUB, sy * Y_TUB, zm) for sx in (-1, 1) for sy in (-1, 1)] +
                       [(sx * (X_TUB - 0.05), sy * (Y_TUB - 0.22), zb) for sx in (-1, 1) for sy in (-1, 1)]))
    # Keel / frame tunnel between the wheels
    parts.append(cbox(-X_NOSE, X_NOSE, -Y_KEEL, Y_KEEL, hz(h_keel), hz(h_arch), 0.03))
    # Front and rear noses with sloped glacis
    for s in (1, -1):
        x0, x1 = X_NOSE, HL - 0.03
        pts = []
        for sy in (-1, 1):
            pts += [(s * x0, sy * 1.0, hz(h_arch)), (s * x0, sy * 1.0, hz(h_nose + 0.12)),
                    (s * (x1 - 0.02), sy * 0.93, hz(h_arch)), (s * (x1 - 0.10), sy * 0.93, hz(h_nose + 0.13)),
                    (s * x1, sy * 0.85, hz(h_arch - 0.05))]
        parts.append(chull(pts))
        # Low sloped hood at the deck ends (cooling intake front, electronics rear)
        parts.append(chull([(s * (HL - 0.75), sy * 0.90, hz(h_deck)) for sy in (-1, 1)] +
                           [(s * (HL - 0.70), sy * 0.86, hz(h_deck + 0.10)) for sy in (-1, 1)] +
                           [(s * (HL - 0.20), sy * 0.86, hz(h_deck + 0.08)) for sy in (-1, 1)] +
                           [(s * (HL - 0.08), sy * 0.90, hz(h_deck)) for sy in (-1, 1)]))
    return cat(parts)


def hull_details():
    p = []
    zt = hz(h_deck)
    # Hatch frames on the deck (genset front, battery centre, electronics rear)
    for (xc, lx, ly) in ((1.25, 0.9, 1.3), (0.0, 1.1, 1.6), (-1.35, 0.9, 1.3)):
        for (dx, dy, sx, sy) in ((0, ly / 2, lx, 0.04), (0, -ly / 2, lx, 0.04), (lx / 2, 0, 0.04, ly), (-lx / 2, 0, 0.04, ly)):
            p.append(cbox(xc + dx - sx / 2, xc + dx + sx / 2, dy - sy / 2, dy + sy / 2, zt, zt + 0.012))
    # Anti-slip ribs on the cargo area
    for i in range(-6, 7):
        p.append(cbox(-1.95, 0.85, i * 0.12 - 0.008, i * 0.12 + 0.008, zt, zt + 0.006))
    # Tie-down rings along the deck edges
    for x in np.linspace(-2.0, 2.0, 6):
        for sy in (-1, 1):
            p.append(ring(0.03, 0.02, 0.012, 16, "x", (x, sy * (HW - 0.12), zt + 0.03)))
    # Grilles in the noses (dark slats)
    for s in (1, -1):
        for k in range(6):
            z = hz(h_nose + 0.20 + k * 0.055)
            p.append(cbox(s * (HL - 0.035) - 0.02, s * (HL - 0.035) + 0.02, -0.55, 0.55, z, z + 0.022))
    # Side storage doors on the tub with hinges and handles
    for sy in (-1, 1):
        y = sy * (Y_TUB + 0.006)
        for xc in (-0.29, 0.29):
            p.append(cbox(xc - 0.26, xc + 0.26, y - 0.006, y + 0.006, hz(h_tub + 0.22), hz(h_arch - 0.06)))
            p.append(cbox(xc - 0.06, xc + 0.06, y + sy * 0.006 - 0.012, y + sy * 0.006 + 0.012,
                          hz(h_tub + 0.45), hz(h_tub + 0.48)))
    # Mud flaps behind each wheel (outboard)
    for sx in (1, -1):
        for sy in (-1, 1):
            xf = sx * XA - 0.62 * sx
            p.append(cbox(xf - 0.01, xf + 0.01, sy * 0.78 - 0.17, sy * 0.78 + 0.17, hz(0.30), hz(h_arch)))
    # Fender skirts: deck edge lip over each wheel
    for sx in (1, -1):
        for sy in (-1, 1):
            p.append(cbox(sx * XA - 0.65, sx * XA + 0.65, sy * HW - 0.03, sy * HW + 0.03, hz(h_arch - 0.07), hz(h_arch)))
    return cat(p)


def hull_steel():
    p = []
    zt = hz(h_deck)
    # Bumpers (box beams) with tow shackles
    for s in (1, -1):
        x0 = s * (HL - 0.11)
        x1 = s * HL
        p.append(cbox(min(x0, x1), max(x0, x1), -0.95, 0.95, hz(h_nose), hz(h_nose + 0.14), 0.015))
        for sy in (-1, 1):
            p.append(ring(0.055, 0.03, 0.03, 20, "y", (s * (HL - 0.02), sy * 0.62, hz(h_nose + 0.07))))
    # Railing around the deck: posts + top rail + mid rail
    rail_h = V["body"]["railing_height"]
    xr, yr = HL - 0.12, HW - 0.06
    corners = [(xr, yr), (-xr, yr), (-xr, -yr), (xr, -yr)]
    for i in range(4):
        a, b = corners[i], corners[(i + 1) % 4]
        for frac in (1.0, 0.5):
            z = zt + rail_h * frac
            p.append(cyl((a[0], a[1], z), (b[0], b[1], z), 0.019, 12))
        n = int(max(abs(b[0] - a[0]), abs(b[1] - a[1])) / 0.8) + 1
        for k in range(n + 1):
            x = a[0] + (b[0] - a[0]) * k / n
            y = a[1] + (b[1] - a[1]) * k / n
            p.append(cyl((x, y, zt), (x, y, zt + rail_h), 0.019, 12))
    for (x, y) in corners:
        p.append(sphere((x, y, zt + rail_h), 0.024, 1))
    # Lidar posts (front and rear, centre)
    for s in (1, -1):
        p.append(cyl((s * (HL - 0.10), 0, zt + 0.08), (s * (HL - 0.10), 0, zt + 0.17), 0.05, 20))
        p.append(cbox(s * (HL - 0.10) - 0.07, s * (HL - 0.10) + 0.07, -0.07, 0.07, zt + 0.17, zt + 0.185))
        p.append(cyl((s * (HL - 0.10), 0, hz(h_deck + 0.10) - 0.02), (s * (HL - 0.10), 0, zt + 0.08), 0.03, 12))
    # Radio antennas (rear corners) and bases
    for sy in (-1, 1):
        x, y = -HL + 0.30, sy * (HW - 0.25)
        p.append(cyl((x, y, zt), (x, y, zt + 0.06), 0.04, 16))
        p.append(cyl((x, y, zt + 0.06), (x, y, zt + 1.10), 0.006, 8))
    # Genset exhaust (rear left of the front hood)
    p.append(cyl((HL - 0.85, 0.70, zt), (HL - 0.85, 0.70, zt + 0.35), 0.04, 16))
    p.append(cyl((HL - 0.85, 0.70, zt + 0.35), (HL - 0.95, 0.70, zt + 0.42), 0.04, 16))
    # Boarding steps on the tub sides
    for sy in (-1, 1):
        y0, y1 = sorted((sy * Y_TUB, sy * (Y_TUB + 0.12)))
        for xc in (-0.29, 0.29):
            p.append(cbox(xc - 0.20, xc + 0.20, y0, y1, hz(h_tub + 0.05), hz(h_tub + 0.07)))
    return cat(p)


def lamps():
    white, amber, red = [], [], []
    for s in (1, -1):
        for sy in (-1, 1):
            x = s * (HL - 0.115)
            if s > 0:
                white.append(cyl((x, sy * 0.78, hz(h_arch - 0.12)), (x + 0.03, sy * 0.78, hz(h_arch - 0.12)), 0.07, 24))
                amber.append(cbox(x - 0.005, x + 0.03, sy * 0.88 - 0.04, sy * 0.88 + 0.04, hz(h_arch - 0.16), hz(h_arch - 0.08)))
            else:
                red.append(cbox(x - 0.03, x + 0.005, sy * 0.78 - 0.07, sy * 0.78 + 0.07, hz(h_arch - 0.17), hz(h_arch - 0.07)))
                amber.append(cbox(x - 0.03, x + 0.005, sy * 0.90 - 0.035, sy * 0.90 + 0.035, hz(h_arch - 0.17), hz(h_arch - 0.07)))
            # Side marker lights
            amber.append(cbox(s * 1.9 - 0.04, s * 1.9 + 0.04, sy * HW - 0.005, sy * HW + 0.005, hz(h_arch + 0.05), hz(h_arch + 0.09)))
        # Work lights on the railing corners
        for sy in (-1, 1):
            x, y, z = s * (HL - 0.12), sy * (HW - 0.06), hz(h_deck) + V["body"]["railing_height"] + 0.06
            white.append(cbox(x - 0.04, x + 0.04, y - 0.06, y + 0.06, z - 0.04, z + 0.04))
    return cat(white), cat(amber), cat(red)


def frame_brackets():
    """Chassis-side suspension hard points: link brackets, coil-over towers,
    Panhard bracket and bump stops, for both axles."""
    L = V["suspension"]["linkage"]
    p = []
    for s in (1, -1):  # front, rear (rear = front rotated by pi about z)
        def w(pt):
            return (s * (XA + pt[0]), s * pt[1], pt[2])
        for sy in (1, -1):
            c = L["lower_link"]["chassis"]
            q = w((c[0], sy * c[1], c[2]))
            p.append(cbox(q[0] - 0.06, q[0] + 0.06, q[1] - 0.05, q[1] + 0.05, q[2] - 0.05, hz(h_tub) + 0.02))
            c = L["coilover"]["chassis"]
            q = w((c[0], sy * c[1], c[2]))
            p.append(cbox(q[0] - 0.08, q[0] + 0.08, q[1] - 0.08, q[1] + 0.08, q[2], hz(h_arch) + 0.001, 0.01))
            # Bump stop under the keel edge: touches the axle tube at full bump
            q = w((0.0, sy * (Y_KEEL - 0.03), 0.0))
            z_stop = V["axle"]["tube_diameter"] / 2 + max(V["suspension"]["travel_bump_front"],
                                                         V["suspension"]["travel_bump_rear"]) + 0.005
            p.append(cyl((q[0], q[1], hz(h_keel) + 0.01), (q[0], q[1], z_stop), 0.045, 16))
        c = L["upper_link"]["chassis"]
        q = w(c)
        p.append(cbox(q[0] - 0.06, q[0] + 0.06, q[1] - 0.06, q[1] + 0.06, q[2] - 0.04, hz(h_keel) + 0.01))
        # Panhard bracket: from the pivot up and inboard to the keel underside
        c = L["panhard_rod"]["chassis"]
        q = w(c)
        yk = s * (Y_KEEL - 0.02)
        p.append(chull([(q[0] - 0.04, q[1] - 0.04, q[2] - 0.05), (q[0] + 0.04, q[1] - 0.04, q[2] - 0.05),
                        (q[0] - 0.04, q[1] + 0.04, q[2] - 0.05), (q[0] + 0.04, q[1] + 0.04, q[2] - 0.05),
                        (q[0] - 0.10, yk, hz(h_keel) + 0.01), (q[0] + 0.10, yk, hz(h_keel) + 0.01),
                        (q[0] - 0.10, yk - s * 0.12, hz(h_keel) + 0.01), (q[0] + 0.10, yk - s * 0.12, hz(h_keel) + 0.01)]))
    return cat(p)


