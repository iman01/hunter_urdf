def tyre():
    # Carcass: revolve a rounded section around the wheel axis (y).
    prof = []
    rs = R_T - 0.05                        # shoulder start
    half = W_T / 2
    n = 10
    for i in range(n + 1):                 # rounded shoulder on each side
        a = math.pi / 2 * i / n
        prof.append((rs + 0.035 * math.sin(a) + 0.0, -half + 0.035 * (1 - math.cos(a))))
    prof = [(R_RIM + 0.015, -half + 0.03)] + [(R_RIM + 0.10, -half - 0.005)] + [(rs - 0.06, -half - 0.01)] + prof
    prof += [(r, -y) for (r, y) in reversed(prof)]
    # revolve() takes (radius, height) about z: build then rotate z -> y
    carcass = revolve(np.array(prof), sections=72)
    carcass.apply_transform(R("x", -math.pi / 2))
    p = [carcass]
    # Tread lugs: two staggered rows of chevron blocks + shoulder lugs
    nl = 36
    for k in range(nl):
        a = 2 * math.pi * k / nl
        for row, sgn in ((0, 1), (1, -1)):
            ang = a + (math.pi / nl if row else 0)
            yc = sgn * W_T * 0.20
            blk = cbox(-0.045, 0.045, -W_T * 0.17, W_T * 0.17, 0.0, 0.022, 0.006)
            blk.apply_transform(R("z", sgn * math.radians(25)))
            blk.apply_translation([0, yc, R_T - 0.022 - 0.0])
            blk.apply_transform(R("y", ang))
            p.append(blk)
            # Shoulder lug wrapping over the tread edge onto the sidewall
            yo = sgn * (W_T / 2 - 0.005)
            sh = chull([(-0.03, yo - sgn * 0.05, R_T - 0.004), (0.03, yo - sgn * 0.05, R_T - 0.004),
                        (-0.03, yo, R_T - 0.012), (0.03, yo, R_T - 0.012),
                        (-0.025, yo + sgn * 0.012, R_T - 0.07), (0.025, yo + sgn * 0.012, R_T - 0.07),
                        (-0.03, yo - sgn * 0.05, R_T - 0.04), (0.03, yo - sgn * 0.05, R_T - 0.04),
                        (-0.025, yo - sgn * 0.01, R_T - 0.08), (0.025, yo - sgn * 0.01, R_T - 0.08)])
            sh.apply_transform(R("y", ang))
            p.append(sh)
    return cat(p)


def rim():
    p = [ring(R_RIM, R_RIM - 0.008, W_RIM, 64, "y", (0, 0, 0)),                   # barrel
         ring(R_RIM - 0.008, R_RIM - 0.05, 0.012, 64, "y", (0, -W_RIM / 2 + 0.006, 0)),  # inner flange
         ring(R_RIM + 0.03, R_RIM - 0.03, 0.022, 64, "y", (0, W_RIM / 2 - 0.004, 0))]    # beadlock ring
    for k in range(24):  # beadlock bolts
        a = 2 * math.pi * k / 24
        r = R_RIM + 0.005
        p.append(cyl((r * math.cos(a), W_RIM / 2 + 0.007, r * math.sin(a)),
                     (r * math.cos(a), W_RIM / 2 + 0.017, r * math.sin(a)), 0.008, 6))
    # Centre disc with 8 holes look (spokes) at the mounting face
    yd = OFF
    p.append(ring(R_RIM - 0.006, 0.09, 0.014, 64, "y", (0, yd, 0)))
    for k in range(8):
        a = 2 * math.pi * (k + 0.5) / 8
        p.append(cyl((0.10 * math.cos(a), yd + 0.008, 0.10 * math.sin(a)),
                     ((R_RIM - 0.02) * math.cos(a), yd + 0.008, (R_RIM - 0.02) * math.sin(a)), 0.016, 8))
    return cat(p)


def hub():
    yd = OFF
    bc = WH["bolt_circle"] / 2
    p = [cyl((0, yd - 0.04, 0), (0, yd + 0.02, 0), 0.095, 32),
         cyl((0, yd + 0.02, 0), (0, yd + 0.075, 0), 0.055, 24)]                  # locking hub cap
    for k in range(WH["bolt_count"]):
        a = 2 * math.pi * k / WH["bolt_count"]
        p.append(cyl((bc * math.cos(a), yd + 0.012, bc * math.sin(a)),
                     (bc * math.cos(a), yd + 0.042, bc * math.sin(a)), 0.014, 6))
    return cat(p)


