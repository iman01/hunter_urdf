HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
V = yaml.safe_load(open(os.path.join(ROOT, "hunter_description", "config", "vehicle.yaml")))

ZG = V["body"]["ground_z"]          # ground height in base_link


def hz(h):
    return h + ZG


# ------------------------------------------------------------------ helpers
def T(x=0.0, y=0.0, z=0.0):
    return trimesh.transformations.translation_matrix([x, y, z])


def R(axis, ang):
    ax = {"x": [1, 0, 0], "y": [0, 1, 0], "z": [0, 0, 1]}[axis]
    return trimesh.transformations.rotation_matrix(ang, ax)


def chull(points):
    return trimesh.convex.convex_hull(np.asarray(points, dtype=float))


def cbox(x0, x1, y0, y1, z0, z1, c=0.0):
    """Axis-aligned box with all edges chamfered by c."""
    if c <= 0:
        return tbox(extents=[x1 - x0, y1 - y0, z1 - z0], transform=T((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2))
    pts = []
    for x in (x0, x1):
        for y in (y0, y1):
            for z in (z0, z1):
                sx, sy, sz = (1 if x == x0 else -1), (1 if y == y0 else -1), (1 if z == z0 else -1)
                pts += [(x + sx * c, y, z), (x, y + sy * c, z), (x, y, z + sz * c)]
    return chull(pts)


def cyl(p0, p1, r, sections=24):
    p0, p1 = np.asarray(p0, float), np.asarray(p1, float)
    v = p1 - p0
    h = float(np.linalg.norm(v))
    m = tcyl(radius=r, height=h, sections=sections)
    # trimesh cylinders are along z, centred
    z = np.array([0, 0, 1.0])
    d = v / h
    axis = np.cross(z, d)
    s = np.linalg.norm(axis)
    if s < 1e-9:
        rot = np.eye(4) if d[2] > 0 else R("x", math.pi)
    else:
        rot = trimesh.transformations.rotation_matrix(math.atan2(s, float(np.dot(z, d))), axis / s)
    m.apply_transform(rot)
    m.apply_translation((p0 + p1) / 2)
    return m


def ring(r_out, r_in, width, sections=48, axis="y", center=(0, 0, 0)):
    m = trimesh.creation.annulus(r_min=r_in, r_max=r_out, height=width, sections=sections)
    if axis == "y":
        m.apply_transform(R("x", math.pi / 2))
    elif axis == "x":
        m.apply_transform(R("y", math.pi / 2))
    m.apply_translation(center)
    return m


def sphere(c, r, sub=2):
    m = icosphere(subdivisions=sub, radius=r)
    m.apply_translation(c)
    return m


def mirror_y(m):
    m = m.copy()
    m.vertices[:, 1] *= -1
    m.invert()  # restore outward normals after reflection
    return m


def cat(parts):
    parts = [p for p in parts if p is not None]
    return trimesh.util.concatenate(parts)


OUT = {}


def save(name, mesh):
    mesh.merge_vertices()
    OUT[name] = mesh


