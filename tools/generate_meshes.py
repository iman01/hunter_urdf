#!/usr/bin/env python3
"""Procedural visual meshes for the HUNTeR replica.

No CAD data of the real vehicle is public, so every part is built here from
the dimensions in hunter_description/config/vehicle.yaml (itself generated by
tools/vehicle_design.py). Meshes are binary STL, metres, X forward, Z up.

Frames
  hull*.stl, lamps_*.stl, frame.stl    base_link
  axle_*.stl, steering_actuator.stl     axle centre, +x pointing away from the vehicle centre (front axle
                                        orientation; the rear axle uses yaw = pi)
  knuckle_{left,right}.stl              kingpin centre of the FRONT knuckles (rear: other side, yaw = pi)
  tyre/rim/hub.stl                      wheel centre, +y outboard (left wheel; right wheel yaw = pi)
  link_rod.stl, coilover_*.stl          unit/normalised parts along +x for the linkage markers
  sensor parts                          their own link frames (see sensors.xacro)

Usage: python3 tools/generate_meshes.py [--out DIR]
"""

from __future__ import annotations

import argparse
import math
import os

import numpy as np
import trimesh
import yaml
from trimesh.creation import box as tbox
from trimesh.creation import cylinder as tcyl
from trimesh.creation import icosphere, revolve

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
V = yaml.safe_load(open(os.path.join(ROOT, "hunter_description", "config", "vehicle.yaml")))

ZG = V["body"]["ground_z"]          # ground height in base_link


def hz(h):
    return h + ZG


# ------------------------------------------------------------------ helpers
def T(x=0.0, y=0.0, z=0.0):
    return trimesh.transformations.translation_matrix([x, y, z])


def R(axis, ang):
    ax = {"x": [1, 0, 0], "y": [0, 1, 0], "z": [0, 0, 1]}[axis]
    return trimesh.transformations.rotation_matrix(ang, ax)


def chull(points):
    return trimesh.convex.convex_hull(np.asarray(points, dtype=float))


def cbox(x0, x1, y0, y1, z0, z1, c=0.0):
    """Axis-aligned box with all edges chamfered by c."""
    if c <= 0:
        return tbox(extents=[x1 - x0, y1 - y0, z1 - z0], transform=T((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2))
    pts = []
    for x in (x0, x1):
        for y in (y0, y1):
            for z in (z0, z1):
                sx, sy, sz = (1 if x == x0 else -1), (1 if y == y0 else -1), (1 if z == z0 else -1)
                pts += [(x + sx * c, y, z), (x, y + sy * c, z), (x, y, z + sz * c)]
    return chull(pts)


def cyl(p0, p1, r, sections=24):
    p0, p1 = np.asarray(p0, float), np.asarray(p1, float)
    v = p1 - p0
    h = float(np.linalg.norm(v))
    m = tcyl(radius=r, height=h, sections=sections)
    # trimesh cylinders are along z, centred
    z = np.array([0, 0, 1.0])
    d = v / h
    axis = np.cross(z, d)
    s = np.linalg.norm(axis)
    if s < 1e-9:
        rot = np.eye(4) if d[2] > 0 else R("x", math.pi)
    else:
        rot = trimesh.transformations.rotation_matrix(math.atan2(s, float(np.dot(z, d))), axis / s)
    m.apply_transform(rot)
    m.apply_translation((p0 + p1) / 2)
    return m


def ring(r_out, r_in, width, sections=48, axis="y", center=(0, 0, 0)):
    m = trimesh.creation.annulus(r_min=r_in, r_max=r_out, height=width, sections=sections)
    if axis == "y":
        m.apply_transform(R("x", math.pi / 2))
    elif axis == "x":
        m.apply_transform(R("y", math.pi / 2))
    m.apply_translation(center)
    return m


def sphere(c, r, sub=2):
    m = icosphere(subdivisions=sub, radius=r)
    m.apply_translation(c)
    return m


def mirror_y(m):
    m = m.copy()
    m.vertices[:, 1] *= -1
    m.invert()  # restore outward normals after reflection
    return m


def cat(parts):
    parts = [p for p in parts if p is not None]
    return trimesh.util.concatenate(parts)


OUT = {}


def save(name, mesh):
    mesh.merge_vertices()
    OUT[name] = mesh


# =================================================================== HULL
# The hull follows the 2023-2025 vehicle (docs/DESIGN_REPORT.md, source PHOTOS):
# a closed, faceted, windowless body built from flat plates. It is assembled
# from convex pieces (convex hulls of the corner points below):
#   upper hull ("cap")  full width over the wheels, from the arch tops to the deck
#   nose block          sloped glacis above the black sensor band
#   sensor band         full-width black strip, centre flat, ends wrapped back
#   chin                lower nose plates converging on the tow bar
#   tub                 between the wheels, side panels leaning inward
#   rear                stepped-down dark rear deck with a steep rear face, olive rear panel
# Heights in the body parameters are above ground; hz() converts to base_link.
B = V["body"]
HL = B["length"] / 2
HW = B["width"] / 2
H_DECK, H_ARCH = B["deck_height"], B["wheel_arch_height"]
Y_CH, Y_DK = B["chine_half_width"], B["deck_half_width"]
X_DF, Y_DF = B["deck_front_x"], B["deck_front_half_width"]
H_BT, H_BB = B["band_top_height"], B["band_bottom_height"]
Y_BF, X_BC, Y_BD = B["band_flat_half_width"], B["band_corner_x"], B["band_half_width"]
H_CB, Y_CN = B["chin_bottom_height"], B["chin_half_width"]
H_NB, H_RB = B["nose_bottom_height"], B["rear_bottom_height"]
h_tub, h_keel = B["belly_height"], B["keel_height"]
X_TUB, Y_TUB, Y_TUBB, Y_KEEL = B["tub_half_length"], B["tub_half_width"], B["tub_bottom_half_width"], B["keel_half_width"]
X_NOSE = B["nose_start"]
X_TUBB = B["tub_bottom_half_length"]
X_TR, X_TE, H_TR, H_TT = B["rear_tray_start"], B["rear_tray_end"], B["rear_tray_height"], B["rear_panel_top_height"]
H_TRE, H_TPB = B["rear_deck_edge_height"], B["rear_panel_bottom_height"]
X_FACE = HL - 0.02                    # front face of the band / rear panel
X_DC = X_DF - 0.14                    # deck front corner (chamfer)
H_TUB_MID = 0.75
Y_TUB_MID = 0.92
X_TUB_MID = X_TUBB + (H_TUB_MID - h_tub) / (H_ARCH - h_tub) * (X_TUB - X_TUBB)
WB = V["chassis"]["wheelbase"]
XA = WB / 2
OR = B["outrigger"]
h_arch = H_ARCH                       # used by frame_brackets()


def P(x, y, h):
    """Point with a height above ground."""
    return (x, y, hz(h))


def both(f):
    """Points for y and -y."""
    return [q for sy in (1, -1) for q in f(sy)]


def flank_y(h):
    return Y_CH - (h - H_ARCH) / (H_DECK - H_ARCH) * (Y_CH - Y_DK)


def nose_outline(h, x_face=X_FACE, y_flat=Y_BF, grow=0.0):
    """Plan outline of the nose/tail at height h: flat centre, angled ends, short sides (front, +x)."""
    return both(lambda sy: [P(x_face + grow, sy * y_flat, h), P(X_BC + grow * 0.5, sy * (Y_BD + grow), h),
                            P(X_NOSE, sy * (Y_BD + grow), h)])


def mx(points):
    """Mirror points front <-> rear (x -> -x)."""
    return [(-x, y, z) for (x, y, z) in points]


def cap_main():
    return chull(both(lambda sy: [P(X_DF, sy * Y_DF, H_DECK), P(X_DC, sy * Y_DK, H_DECK), P(X_TR, sy * Y_DK, H_DECK),
                                  P(X_NOSE + 0.05, sy * Y_CH, H_ARCH), P(X_TR, sy * Y_CH, H_ARCH)]))


def nose_block():
    return chull(nose_outline(H_BT) + both(lambda sy: [P(X_NOSE + 0.05, sy * Y_CH, H_ARCH), P(X_DF, sy * Y_DF, H_DECK),
                                                       P(X_DC, sy * Y_DK, H_DECK)]))


def band():
    return chull(nose_outline(H_BT - 0.002, grow=0.004) + nose_outline(H_BB + 0.002, grow=0.004))


def chin():
    return chull(nose_outline(H_BB) + both(lambda sy: [P(X_FACE - 0.02, sy * Y_CN, H_CB), P(X_NOSE, sy * Y_CN, H_CB)]))


def tub_x(h):
    """Half-length of the trapezoidal tub side at height h (long at the arch tops, short at the belly)."""
    return X_TUBB + (h - h_tub) / (H_ARCH - h_tub) * (X_TUB - X_TUBB)


def tub():
    return chull([P(sx * X_TUB, sy * Y_TUB, H_ARCH) for sx in (-1, 1) for sy in (-1, 1)] +
                 [P(sx * X_TUB_MID, sy * Y_TUB_MID, H_TUB_MID) for sx in (-1, 1) for sy in (-1, 1)] +
                 [P(sx * X_TUBB, sy * Y_TUBB, h_tub) for sx in (-1, 1) for sy in (-1, 1)])


def rear_upper():
    """Dark rear section behind the deck step: gently sloping rear deck, steep rear face (PHOTOS)."""
    y_deck = Y_DK - 0.02
    return chull(mx(nose_outline(H_TT, y_flat=0.60)) +
                 both(lambda sy: [P(X_TR, sy * y_deck, H_TR), P(X_TE, sy * y_deck, H_TRE),
                                  P(X_TR, sy * Y_CH, H_ARCH), P(-(X_NOSE + 0.05), sy * Y_CH, H_ARCH)]))


def rear_end():
    """Olive rear panel with chamfered corners; open underneath (axle and links visible)."""
    return chull(mx(nose_outline(H_TT, y_flat=0.60)) + mx(nose_outline(H_TPB, y_flat=0.58, grow=-0.03)))


def hull():
    """Olive-green body panels."""
    return cat([cap_main(), nose_block(), chin(), tub(), rear_end()])


def hull_black():
    """Black parts: front sensor band, cooling louvres."""
    p = [band()]
    # Louvred grille low on each tub side (PHOTOS: horizontal vent between the wheels)
    for sy in (1, -1):
        for k in range(4):
            t = 0.18 + 0.2 * k
            y = sy * (Y_TUB_MID + (Y_TUBB - Y_TUB_MID) * t + 0.006)
            h = H_TUB_MID + (h_tub - H_TUB_MID) * t
            p.append(chull([P(x, y, h + dh) for x in (-0.32, 0.32) for dh in (-0.012, 0.012)] +
                           [P(x, y - sy * 0.012, h + dh) for x in (-0.32, 0.32) for dh in (-0.012, 0.012)]))
    return cat(p)


def hull_trim():
    """Dark anthracite: wheel-arch outlines and the whole rear section above the rear panel."""
    p = [rear_upper()]
    for s in (1, -1):
        for sy in (1, -1):
            # Lip along the arch top, slightly proud of the hull side
            x0, x1 = sorted((s * (X_TUB - 0.02), s * (X_NOSE + 0.03)))
            p.append(chull([P(x, sy * yy, h) for x in (x0, x1)
                            for (yy, h) in ((Y_CH + 0.012, H_ARCH - 0.04), (Y_CH + 0.012, H_ARCH + 0.025),
                                            (Y_CH - 0.10, H_ARCH - 0.04), (Y_CH - 0.10, H_ARCH))]))
            # Inner edge of the arch along the inclined tub end (PHOTOS: wide slanted plate)
            pts = []
            for (yy, h) in ((Y_TUB, H_ARCH), (Y_TUB_MID, H_TUB_MID), (Y_TUBB + 0.05, h_tub + 0.06)):
                xa, xb = sorted((s * (tub_x(h) - 0.10), s * (tub_x(h) + 0.012)))
                pts += [P(x, sy * (yy + 0.012), h) for x in (xa, xb)] + [P(x, sy * (yy - 0.08), h) for x in (xa, xb)]
            p.append(chull(pts))
            # Outer edge of the arch on the nose / tail block: band end down the lower plate to the tow bar
            xa, xb = sorted((s * (X_NOSE - 0.012), s * (X_NOSE + 0.035)))
            segs = [((Y_CH, H_ARCH), (Y_BD, H_BB)), ((Y_BD, H_BB), (Y_CN, H_CB))] if s > 0 else \
                [((Y_CH, H_ARCH), (Y_BD - 0.03, H_TPB))]
            for (ya, ha), (yb, hb) in segs:
                p.append(chull([P(x, sy * (yy + 0.012), hh) for x in (xa, xb) for (yy, hh) in ((ya, ha), (yb, hb))] +
                               [P(x, sy * (yy - 0.07), hh) for x in (xa, xb) for (yy, hh) in ((ya, ha), (yb, hb))]))
    return cat(p)


def hull_plates():
    """Lighter olive name plates on the chin (front) and rear panel."""
    p = [chull([P(X_FACE - 0.02 * (H_BB - h) / (H_BB - H_CB) + dx, y, h) for y in (-0.46, 0.46)
                for h in (H_CB + 0.04, H_BB - 0.035) for dx in (0.0, 0.007)])]
    p.append(chull([P(-(X_FACE + dx), y, h) for y in (-0.30, 0.30) for h in (H_BB - 0.13, H_BB - 0.02)
                    for dx in (0.0, 0.007)]))
    return cat(p)


def hull_glass():
    """Camera / sensor windows in the centre of the black band (PHOTOS)."""
    p = []
    hc = 0.5 * (H_BT + H_BB)
    for (y, w, hh) in ((-0.33, 0.10, 0.07), (-0.16, 0.09, 0.06), (0.16, 0.09, 0.06), (0.33, 0.10, 0.07)):
        p.append(cbox(X_FACE + 0.003, X_FACE + 0.010, y - w / 2, y + w / 2, hz(hc - hh / 2), hz(hc + hh / 2), 0.004))
    return cat(p)


def bolt(c, n, r=0.011):
    n = np.asarray(n, float) / np.linalg.norm(n)
    c = np.asarray(c, float)
    return cyl(c - 0.003 * n, c + 0.006 * n, r, 6)


def hull_details():
    """Dark green: frame tunnel (keel) seen through the arches, and bolt rows along the plate edges
    (PHOTOS: visible on every panel)."""
    p = [cbox(-X_NOSE, X_NOSE, -Y_KEEL, Y_KEEL, hz(h_keel), hz(H_ARCH), 0.03)]
    L = math.hypot(X_DF - X_FACE, H_DECK - H_BT)
    u = np.array([(X_DF - X_FACE) / L, 0.0, (H_DECK - H_BT) / L])       # up the glacis
    n = np.array([(H_DECK - H_BT) / L, 0.0, (X_FACE - X_DF) / L])       # glacis normal
    for y in np.linspace(-Y_DF + 0.06, Y_DF - 0.06, 11):
        p.append(bolt(np.array(P(X_DF, y, H_DECK)) - 0.045 * u, n))
    for y in np.linspace(-Y_BF + 0.04, Y_BF - 0.04, 8):
        p.append(bolt(np.array(P(X_FACE, y, H_BT)) + 0.045 * u, n))
    fl = np.array([0.0, H_DECK - H_ARCH, Y_CH - Y_DK])                  # flank normal (y, z) for sy = +1
    fl = fl / np.linalg.norm(fl)
    for sy in (1, -1):
        for x in np.arange(X_TR + 0.10, X_DC - 0.05, 0.26):
            p.append(bolt(P(x, sy * (Y_DK - 0.035), H_DECK), (0, 0, 1)))
            for h in (H_DECK - 0.035, H_ARCH + 0.04):
                p.append(bolt(P(x, sy * (flank_y(h) + 0.002), h), (0, sy * fl[1], fl[2])))
        for h in np.linspace(H_CB + 0.05, H_BB - 0.04, 3):              # chin plate edges
            p.append(bolt(P(X_FACE - 0.02 * (H_BB - h) / (H_BB - H_CB) + 0.002, sy * (Y_CN - 0.02), h), (1, 0, 0)))
    for y in np.linspace(-0.52, 0.52, 7):                               # rear panel top and bottom edges
        for h in (H_TT - 0.035, H_TPB + 0.035):
            p.append(bolt(P(-(X_FACE + 0.002), y, h), (-1, 0, 0)))
    return cat(p)


def handle(x, y, h, length=0.30, height=0.07, r=0.013):
    return cat([cyl((x - length / 2, y, hz(h)), (x - length / 2, y, hz(h) + height), r, 10),
                cyl((x + length / 2, y, hz(h)), (x + length / 2, y, hz(h) + height), r, 10),
                cyl((x - length / 2, y, hz(h) + height), (x + length / 2, y, hz(h) + height), r, 10)])


def hull_steel():
    p = []
    # Tow bars with brackets and a central tow eye; the shackles are separate meshes
    for s, hb, h_mount in ((1, H_NB, H_CB), (-1, H_RB, H_TPB)):
        x0, x1 = sorted((s * (HL - 0.10), s * HL))
        p.append(cbox(x0, x1, -0.52, 0.52, hz(hb), hz(hb + 0.12), 0.012))
        for sy in (1, -1):
            xb0, xb1 = sorted((s * (HL - 0.30), s * (HL - 0.08)))
            p.append(cbox(xb0, xb1, sy * 0.22 - 0.04, sy * 0.22 + 0.04, hz(hb + 0.02), hz(h_mount + 0.01)))
        xe0, xe1 = sorted((s * (HL - 0.01), s * (HL + 0.045)))
        p.append(cbox(xe0, xe1, -0.05, 0.05, hz(hb + 0.02), hz(hb + 0.10), 0.01))
    # Grab handles along the deck edges
    for x in (1.42, 0.62, -0.55, -1.30):
        for sy in (1, -1):
            p.append(handle(x, sy * (Y_DK - 0.10), H_DECK))
    # Lidar posts: front at the deck front edge, rear rising from the rear deck
    for sensor in V["sensors"]:
        if sensor["type"] != "lidar":
            continue
        x, y, z = sensor["xyz"]
        base = hz(H_DECK) if x > 0 else hz(rear_deck_h(x))
        p.append(cyl((x, y, base), (x, y, z - 0.004), 0.04, 20))
        p.append(cbox(x - 0.07, x + 0.07, y - 0.07, y + 0.07, z - 0.012, z, 0.004))
        p.append(cbox(x - 0.09, x + 0.09, y - 0.09, y + 0.09, base, base + 0.012))
    # Outriggers at the front deck corners (PHOTOS): arm from the deck corner up and outboard
    for sy in (1, -1):
        root = (X_DC - 0.08, sy * (Y_DK - 0.06), hz(H_DECK))
        head = (OR[0], sy * OR[1], hz(OR[2]) - 0.045)
        p.append(cbox(root[0] - 0.06, root[0] + 0.06, root[1] - 0.06, root[1] + 0.06, root[2], root[2] + 0.02))
        p.append(cyl(root, head, 0.022, 12))
        p.append(cbox(head[0] - 0.05, head[0] + 0.05, head[1] - 0.04, head[1] + 0.04, head[2] - 0.01, head[2] + 0.01))
        if sy < 0:                                                   # work light / camera housing, right side
            p.append(cbox(head[0] - 0.05, head[0] + 0.06, head[1] - 0.05, head[1] + 0.05, head[2] + 0.01,
                          head[2] + 0.10, 0.008))
    # Rear camera post at the right rear deck corner
    for sensor in V["sensors"]:
        if sensor["name"] == "top_rear_camera":
            x, y, z = sensor["xyz"]
            p.append(cyl((x + 0.05, y, hz(rear_deck_h(x + 0.05))), (x + 0.05, y, z - 0.04), 0.022, 12))
            p.append(cbox(x - 0.02, x + 0.08, y - 0.04, y + 0.04, z - 0.05, z - 0.03))
    # Radio antennas (PHOTOS): two whips at the deck sides, a tall thin one at the left rear corner
    for (x, y, length, r) in ((-0.40, Y_DK - 0.16, 1.00, 0.007), (-0.40, -(Y_DK - 0.16), 1.00, 0.007),
                              (X_TE + 0.10, Y_DK - 0.12, 1.30, 0.005)):
        h0 = hz(H_DECK) if x > X_TR else hz(rear_deck_h(x))
        p.append(cyl((x, y, h0), (x, y, h0 + 0.06), 0.035, 16))
        p.append(cyl((x, y, h0 + 0.06), (x, y, h0 + 0.06 + length), r, 8))
    return cat(p)


def rear_deck_h(x):
    """Height above ground of the sloping rear deck at x (X_TR .. X_TE)."""
    return H_TR + (x - X_TR) / (X_TE - X_TR) * (H_TRE - H_TR)


def tiedowns():
    """Orange tie-down rings on the rear deck (PHOTOS)."""
    p = []
    for x in (X_TR - 0.12, X_TE + 0.30):
        for sy in (1, -1):
            p.append(ring(0.035, 0.022, 0.014, 16, "x", (x, sy * (Y_DK - 0.18), hz(rear_deck_h(x)) + 0.03)))
    return cat(p)


def shackles():
    """Bow shackles on both tow bars: galvanised bodies and blue pins (PHOTOS)."""
    body, pins = [], []
    for s, hb in ((1, H_NB), (-1, H_RB)):
        for sy in (1, -1):
            x, y, z = s * (HL + 0.01), sy * 0.40, hz(hb) + 0.005
            body.append(ring(0.052, 0.034, 0.02, 20, "x", (x, y, z - 0.03)))
            for dy in (-0.035, 0.035):
                body.append(cyl((x, y + dy, z - 0.03), (x, y + dy, z + 0.03), 0.011, 8))
            pins.append(cyl((x, y - 0.06, z + 0.03), (x, y + 0.06, z + 0.03), 0.013, 12))
    return cat(body), cat(pins)


def lamps():
    white, amber, red = [], [], []
    hc = 0.5 * (H_BT + H_BB)
    for sy in (1, -1):
        # Front: two round LED lamps on each wrapped end of the sensor band
        a = np.array([X_FACE, sy * Y_BF])
        c = np.array([X_BC, sy * Y_BD])
        d = (c - a) / np.linalg.norm(c - a)
        nrm = np.array([d[1], -d[0]]) * sy                           # outward in plan
        if nrm[0] < 0:
            nrm = -nrm
        for t in (0.27, 0.63):
            q = a + (c - a) * t
            white.append(cyl((q[0], q[1], hz(hc)), (q[0] + 0.012 * nrm[0], q[1] + 0.012 * nrm[1], hz(hc)), 0.045, 24))
        # Rear: red tail lamp and amber indicator on each angled corner of the rear panel
        a = np.array([-X_FACE, sy * 0.60])
        c = np.array([-X_BC, sy * Y_BD])
        d = (c - a) / np.linalg.norm(c - a)
        nrm = np.array([d[1], -d[0]])
        if nrm[0] > 0:
            nrm = -nrm
        for t, lst in ((0.28, red), (0.62, amber)):
            q = a + (c - a) * t
            pts = []
            for e in (-0.05, 0.05):
                for hh in (H_TT - 0.14, H_TT - 0.06):
                    base = q + d * e
                    pts += [P(base[0], base[1], hh), P(base[0] + 0.012 * nrm[0], base[1] + 0.012 * nrm[1], hh)]
            lst.append(chull(pts))
        # Side markers high on the flanks: amber near the front, red near the rear
        for x, lst in ((X_DC - 0.05, amber), (X_TR + 0.12, red)):
            h = H_ARCH + 0.10
            y = sy * (flank_y(h) + 0.004)
