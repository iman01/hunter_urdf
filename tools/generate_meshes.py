#!/usr/bin/env python3
"""Procedural visual meshes for the HUNTeR replica.

No CAD data of the real vehicle is public, so every part is built here from
the dimensions in hunter_description/config/vehicle.yaml (itself generated by
tools/vehicle_design.py). Meshes are binary STL, metres, X forward, Z up.

Frames
  hull_*.stl, lamps_*.stl, frame.stl   base_link
  axle_*.stl, steering_actuator.stl     axle centre, +x pointing away from the vehicle centre (front axle
                                        orientation; the rear axle uses yaw = pi)
  knuckle_{left,right}.stl              kingpin centre of the FRONT knuckles (rear: other side, yaw = pi)
  tyre/rim/hub.stl                      wheel centre, +y outboard (left wheel; right wheel yaw = pi)
  link_rod.stl, coilover_*.stl          unit/normalised parts along +x for the linkage markers
  sensors and payload parts             their own link frames (see sensors.xacro / payloads.xacro)

Usage: python3 tools/generate_meshes.py [--out DIR]
"""

