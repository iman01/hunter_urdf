def frame_brackets():
    """Chassis-side suspension hard points: link brackets, coil-over towers,
    Panhard bracket and bump stops, for both axles."""
    L = V["suspension"]["linkage"]
    p = []
    for s in (1, -1):  # front, rear (rear = front rotated by pi about z)
        def w(pt):
            return (s * (XA + pt[0]), s * pt[1], pt[2])
        for sy in (1, -1):
            c = L["lower_link"]["chassis"]
            q = w((c[0], sy * c[1], c[2]))
            p.append(cbox(q[0] - 0.06, q[0] + 0.06, q[1] - 0.05, q[1] + 0.05, q[2] - 0.05, hz(h_tub) + 0.02))
